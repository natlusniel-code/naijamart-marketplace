/**
 * Nigerias states and local government areas - the single source of truth.
 *
 * -- Why this file exists ------------------------------------------------------
 * The LGA selector used to be driven by a hand-written stub covering only 8
 * states and ~44 LGAs in total. Choosing any other state produced an EMPTY
 * "City / LGA" dropdown, and even the eight covered states were badly
 * incomplete (Ogun had 8 of its 20 LGAs, Lagos 8 of 20). A seller in Benue, or
 * in Abeokuta North, simply could not state where they were.
 *
 * This file carries the complete official list: 774 LGAs across 36 states and
 * the FCT (768 LGAs + 6 area councils in the FCT = 774), matching INECs
 * per-state counts exactly. `npm test` asserts the total and every per-state
 * count, so a future edit that drops a row fails the test run rather than
 * silently shrinking somebodys dropdown.
 *
 * -- Provenance ---------------------------------------------------------------
 * Names follow INEC / official spelling. Two upstream spellings were
 * normalised: DanDume -> Dandume (Katsina), and the FCTs Abuja area council ->
 * "Abuja Municipal (AMAC)", which is how it is officially named.
 *
 * -- Editing rules ------------------------------------------------------------
 *  - Keep the state keys EXACTLY as they appear in NIGERIA_STATES.
 *  - Keep each list alphabetical (the selectors render it verbatim).
 *  - If you add or remove a row, update EXPECTED_LGA_COUNTS too - the test
 *    compares against it and against the 774 total.
 */

